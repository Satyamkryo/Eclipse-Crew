import "server-only";

import { mkdir, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { and, desc, eq } from "drizzle-orm";

import type { getDatabase } from "../../db/client";
import { agents, memoryEntries } from "../../db/schema";
import { cleanMemoryText, type MemoryDocument } from "./schema";

type Database = Awaited<ReturnType<typeof getDatabase>>;
type MirrorReason = "not_writable" | "missing";

const HEADER = "<!-- Generated by Eclipse Crew from memory in Postgres. Edits to this file are not read back. -->\n\n";
const DOC_FILE: Record<MemoryDocument, string> = { user: "USER.md", memory: "MEMORY.md", private: "PRIVATE.md" };

const chains = new Map<string, Promise<unknown>>();
const statuses = new Map<string, { ok: boolean; reason: MirrorReason | null }>();

function mirrorRoot(): string {
  return process.env.MEMORY_MIRROR_DIR ?? "/var/eclipse/memory";
}

function statusKey(ownerId: string, agentId: string | null): string {
  return `${ownerId}:${agentId ?? "crew"}`;
}

export function getMirrorStatus(ownerId: string, agentId: string | null): { ok: boolean; reason: MirrorReason | null } {
  return statuses.get(statusKey(ownerId, agentId)) ?? { ok: true, reason: null };
}

export function renderDocument(doc: MemoryDocument, entries: { title: string; body: string; pinned: boolean }[]): string {
  const lines = [HEADER.trimEnd(), "", doc === "user" ? "# USER.md" : doc === "memory" ? "# MEMORY.md" : "# Private notes", ""];
  for (const entry of entries) {
    lines.push(`## ${cleanMemoryText(entry.title, 80)}${entry.pinned ? " (pinned)" : ""}`, "", cleanMemoryText(entry.body, 600), "");
  }
  if (entries.length === 0) lines.push("_No entries._", "");
  return lines.join("\n");
}

async function writeAtomic(file: string, text: string): Promise<void> {
  await mkdir(path.dirname(file), { recursive: true });
  const temp = `${file}.${process.pid}.${Date.now()}.tmp`;
  await writeFile(temp, text, { encoding: "utf8", mode: 0o600 });
  await rename(temp, file);
}

async function entriesFor(database: Database, ownerId: string, doc: MemoryDocument, agentId: string | null) {
  const conditions = [eq(memoryEntries.ownerId, ownerId), eq(memoryEntries.doc, doc), eq(memoryEntries.status, "active")];
  if (doc !== "user" && agentId) conditions.push(eq(memoryEntries.agentId, agentId));
  return database.select({ title: memoryEntries.title, body: memoryEntries.body, pinned: memoryEntries.pinned })
    .from(memoryEntries).where(and(...conditions)).orderBy(desc(memoryEntries.pinned), desc(memoryEntries.updatedAt));
}

async function regenerate(database: Database, ownerId: string, agentId: string | null): Promise<void> {
  const root = mirrorRoot();
  await mkdir(root, { recursive: true });
  await writeAtomic(path.join(root, DOC_FILE.user), renderDocument("user", await entriesFor(database, ownerId, "user", null)));
  if (!agentId) return;
  const agentRows = await database.select({ soulMd: agents.soulMd }).from(agents)
    .where(and(eq(agents.ownerId, ownerId), eq(agents.id, agentId))).limit(1);
  if (!agentRows[0]) return;
  const folder = path.join(root, "agents", agentId);
  await writeAtomic(path.join(folder, "SOUL.md"), `${HEADER.trimEnd()}\n\n# SOUL.md\n\n${agentRows[0].soulMd}\n`);
  await writeAtomic(path.join(folder, DOC_FILE.memory), renderDocument("memory", await entriesFor(database, ownerId, "memory", agentId)));
  await writeAtomic(path.join(folder, DOC_FILE.private), renderDocument("private", await entriesFor(database, ownerId, "private", agentId)));
}

// One rewrite per document key at a time: a late commit can never overwrite a newer one with older text. A mirror
// failure never fails the owner's write; the Memory tab reads the fixed reason.
export async function scheduleMirror(database: Database, ownerId: string, agentId: string | null): Promise<{ ok: boolean; reason: MirrorReason | null }> {
  const key = statusKey(ownerId, agentId);
  const previous = chains.get(key) ?? Promise.resolve();
  const next = previous.catch(() => undefined).then(async () => {
    try {
      await regenerate(database, ownerId, agentId);
      statuses.set(key, { ok: true, reason: null });
    } catch (error) {
      const code = (error as { code?: string } | null)?.code;
      statuses.set(key, { ok: false, reason: code === "ENOENT" ? "missing" : "not_writable" });
    }
  });
  chains.set(key, next);
  await next;
  return getMirrorStatus(ownerId, agentId);
}
