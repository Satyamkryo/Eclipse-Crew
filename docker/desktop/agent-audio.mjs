import { spawn } from "node:child_process";
import { randomBytes } from "node:crypto";
import { constants } from "node:fs";
import { chmod, lstat, mkdir, open, unlink } from "node:fs/promises";
import { setTimeout as delay } from "node:timers/promises";
import { validateWave } from "./controller-schema.mjs";

const SINK = "eclipse";
const MAX_SAMPLE_BYTES = 2 * 1024 * 1024;
const fail = (code) => { throw Object.assign(Error(code), { code }); };

// One unprivileged PulseAudio daemon and null sink per graphical session. The socket and cookie live
// under the session's mode-700 runtime; no system bus, TCP listener, hardware device or anonymous auth.
export class AgentAudio {
  constructor({ directory, home, uid, env }) {
    if (typeof directory !== "string" || !/^\/tmp\/ec-\d+-[A-Za-z0-9]{6}$/.test(directory)) fail("invalid_audio_path");
    if (typeof home !== "string" || !/^\/workspace\/homes\/[0-9a-f-]+$/.test(home)) fail("invalid_audio_path");
    if (!Number.isInteger(uid) || uid < 20000 || uid > 59999) fail("invalid_audio_path");
    if (!env || typeof env !== "object" || Array.isArray(env)) fail("invalid_audio_path");
    this.directory = directory; this.home = home; this.uid = uid; this.env = env;
    this.runtime = `${directory}/pulse`;
    this.pulseHome = `${this.runtime}/home`;
    this.socket = `${this.runtime}/native`;
    this.cookie = `${this.pulseHome}/.config/pulse/cookie`;
    this.config = `${directory}/pulse.conf`;
    this.child = null; this.started = false; this.captureController = null; this.captureChild = null;
  }

  async prepareDirectory(path) {
    try {
      const stat = await lstat(path);
      if (!stat.isDirectory() || stat.isSymbolicLink() || stat.uid !== this.uid || (stat.mode & 0o7777) !== 0o700) fail("unsafe_audio_path");
      return;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      await mkdir(path, { mode: 0o700 }); await chmod(path, 0o700);
    }
  }

  async writeOnce(path, bytes) {
    try {
      const stat = await lstat(path);
      if (stat.isSymbolicLink() || !stat.isFile() || stat.uid !== this.uid || (stat.mode & 0o7777) !== 0o600 || stat.nlink !== 1) fail("unsafe_audio_path");
      return;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      const file = await open(path, "wx", 0o600);
      try { await file.writeFile(bytes); } finally { await file.close(); }
    }
  }

  async start() {
    if (this.started) return;
    await this.prepareDirectory(this.runtime);
    await this.prepareDirectory(this.pulseHome);
    await this.prepareDirectory(`${this.pulseHome}/.config`);
    await this.prepareDirectory(`${this.pulseHome}/.config/pulse`);
    await this.writeOnce(this.config, `# Generated by Eclipse Crew.\n.fail\nload-module module-native-protocol-unix socket=${this.socket} auth-anonymous=0 auth-cookie-enabled=1\nload-module module-null-sink sink_name=${SINK} sink_properties=device.description=EclipseAudio\nset-default-sink ${SINK}\n`);
    await this.writeOnce(this.cookie, randomBytes(256));
    const env = { ...this.env, HOME: this.pulseHome, XDG_CONFIG_HOME: `${this.pulseHome}/.config`, XDG_RUNTIME_DIR: this.runtime, PULSE_RUNTIME_PATH: this.runtime };
    delete env.PULSE_SERVER; delete env.PULSE_COOKIE; delete env.PULSE_SINK;
    const child = spawn("pulseaudio", ["--daemonize=no", "--exit-idle-time=-1", "--disallow-exit", "--log-target=stderr", "--log-level=error",
      "-n", `--file=${this.config}`], { env, shell: false, stdio: ["ignore", "ignore", "pipe"] });
    this.child = child;
    child.once("error", () => { if (this.child === child) { this.child = null; this.started = false; } });
    child.once("exit", () => { if (this.child === child) { this.child = null; this.started = false; } });
    for (let i = 0; i < 80; i++) {
      if (!this.child) fail("audio_unavailable");
      let socket, cookie;
      try { socket = await lstat(this.socket); cookie = await lstat(this.cookie); } catch (error) {
        if (error.code !== "ENOENT") throw error;
        await delay(100); continue;
      }
      if (!socket.isSocket() || socket.uid !== this.uid) fail("audio_unavailable");
      if (!cookie.isFile() || cookie.isSymbolicLink() || cookie.uid !== this.uid) fail("audio_unavailable");
      if ((cookie.mode & 0o777) !== 0o600) await chmod(this.cookie, 0o600);
      this.started = true;
      Object.assign(this.env, { PULSE_SERVER: `unix:${this.socket}`, PULSE_COOKIE: this.cookie, PULSE_SINK: SINK });
      return;
    }
    fail("audio_unavailable");
  }

  cancel() {
    this.captureController?.abort();
    try { this.captureChild?.kill("SIGKILL"); } catch { /* already exited */ }
  }

  async capture(seconds, signal) {
    if (!Number.isInteger(seconds) || seconds < 1 || seconds > 30) fail("invalid_audio");
    if (signal?.aborted) fail("capture_cancelled");
    if (!this.started) await this.start();
    const controller = new AbortController(); this.captureController = controller;
    const forward = () => controller.abort();
    signal?.addEventListener("abort", forward, { once: true });
    const path = `${this.directory}/audio-${randomBytes(8).toString("hex")}.wav`;
    const placeholder = await open(path, "wx", 0o600); await placeholder.close();
    try {
      await new Promise((resolve, reject) => {
        let settled = false, timer, abort;
        const finish = (error) => {
          if (settled) return; settled = true; clearTimeout(timer); controller.signal.removeEventListener("abort", abort);
          if (error) reject(error); else resolve();
        };
        let child;
        try {
          child = spawn("ffmpeg", ["-nostdin", "-hide_banner", "-loglevel", "error", "-f", "pulse", "-i", `${SINK}.monitor`,
            "-t", String(seconds), "-ac", "1", "-ar", "24000", "-c:a", "pcm_s16le", "-map_metadata", "-1", "-y", path],
            { env: this.env, shell: false, stdio: ["ignore", "ignore", "pipe"] });
        } catch { finish(fail("audio_capture_failed")); return; }
        this.captureChild = child;
        let stderr = ""; child.stderr.on("data", (chunk) => { if (stderr.length < 2048) stderr += String(chunk); });
        abort = () => { try { child.kill("SIGKILL"); } catch { /* exited */ } finish(fail("capture_cancelled")); };
        timer = setTimeout(() => { try { child.kill("SIGKILL"); } catch { /* exited */ } finish(fail("audio_capture_failed")); }, (seconds + 5) * 1000);
        controller.signal.addEventListener("abort", abort, { once: true });
        child.once("error", () => finish(fail("audio_capture_failed")));
        child.once("exit", (code) => {
          this.captureChild = null;
          if (code === 0) finish(null); else finish(fail("audio_capture_failed"));
        });
      });
      const file = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW);
      try {
        const stat = await file.stat();
        if (!stat.isFile() || stat.uid !== this.uid || (stat.mode & 0o777) !== 0o600 || stat.nlink !== 1 ||
            stat.size < 44 || stat.size > MAX_SAMPLE_BYTES + 64) fail("audio_capture_failed");
        const wav = await file.readFile();
        let durationMs;
        try { ({ durationMs } = validateWave(wav)); } catch { fail("audio_capture_failed"); }
        if (durationMs > seconds * 1000 + 500) fail("audio_capture_failed");
        return { wav, durationMs };
      } finally { await file.close(); }
    } finally {
      this.captureController = null; this.captureChild = null;
      signal?.removeEventListener("abort", forward);
      await unlink(path).catch(() => {});
    }
  }

  async stop() {
    this.cancel();
    const child = this.child; this.child = null; this.started = false;
    if (!child) return;
    await new Promise((resolve) => {
      const timer = setTimeout(resolve, 1500);
      child.once("exit", () => { clearTimeout(timer); resolve(); });
      try { child.kill("SIGTERM"); } catch { clearTimeout(timer); resolve(); }
    });
    if (child.exitCode === null && child.signalCode === null) { try { child.kill("SIGKILL"); } catch { /* exited */ } }
  }
}
