async function ensureDirectory(path, uid) {
  let stat;
  try { stat = await lstat(path); } catch (error) {
    if (error.code !== "ENOENT") throw error;
    await mkdir(path, { mode: 0o700 }); await chmod(path, 0o700); stat = await lstat(path);
  }
  if (stat.isSymbolicLink() || !stat.isDirectory() || stat.uid !== uid || (stat.mode & 0o7777) !== 0o700) fail("unsafe_desktop_path");
}

async function writeIfMissing(path, content, uid) {
  let stat;
  try { stat = await lstat(path); } catch (error) {
    if (error.code !== "ENOENT") throw error;
    const file = await open(path, "wx", 0o600);
    try { await file.writeFile(content); } finally { await file.close(); }
    return;
  }
  if (stat.isSymbolicLink() || !stat.isFile() || stat.uid !== uid || (stat.mode & 0o7777) !== 0o600 || stat.nlink !== 1) fail("unsafe_desktop_path");
}

async function linkIfMissing(path, target, uid) {
  let stat;
  try { stat = await lstat(path); } catch (error) {
    if (error.code !== "ENOENT") throw error;
    await symlink(target, path); return;
  }
  // Preserve a user's own entry rather than replacing it.
  if (stat.isSymbolicLink() && stat.uid === uid) await readlink(path);
}

export async function seedDesktop({ home, downloads, uid, launcherDir = DESKTOP_CONFIG_DIR }) {
  if (!Number.isInteger(uid) || uid < 20000 || uid > 59999) fail("invalid_desktop_uid");
  const config = desktopConfig(home, downloads, launcherDir);
  for (const directory of config.directories) await ensureDirectory(directory, uid);
  for (const file of config.files) await writeIfMissing(file.path, file.content, uid);
  for (const link of config.links) await linkIfMissing(link.path, link.target, uid);
  return config;
}
