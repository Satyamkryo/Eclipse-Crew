import { lstat, mkdir, chmod, open, readlink, symlink } from "node:fs/promises";

export const DESKTOP_CONFIG_DIR = "/opt/eclipse/desktop/desktop-config";
const ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const fail = (code) => { throw Error(code); };

export function desktopPaths(home, downloads, launcherDir = DESKTOP_CONFIG_DIR) {
  if (typeof home !== "string" || !/^\/workspace\/homes\/[0-9a-f-]+$/.test(home) || !ID.test(home.slice("/workspace/homes/".length))) fail("invalid_desktop_home");
  if (typeof downloads !== "string" || !/^\/downloads\/[0-9a-f-]+$/.test(downloads) || downloads.slice("/downloads/".length) !== home.slice("/workspace/homes/".length)) fail("invalid_desktop_downloads");
  if (typeof launcherDir !== "string" || !launcherDir.startsWith("/")) fail("invalid_desktop_launcher");
  return {
    home, downloads,
    desktop: `${home}/Desktop`,
    tint2Directory: `${home}/.config/tint2`,
    tint2rc: `${home}/.config/tint2/tint2rc`,
    pcmanfmDirectory: `${home}/.config/pcmanfm/default`,
    pcmanfmConfig: `${home}/.config/pcmanfm/default/pcmanfm.conf`,
    pcmanfmDesktop: `${home}/.config/pcmanfm/default/desktop-items-0.conf`,
    userDirs: `${home}/.config/user-dirs.dirs`,
    applications: `${home}/.local/share/applications`,
    browserDesktop: `${home}/.local/share/applications/eclipse-browser.desktop`,
    filesDesktop: `${home}/.local/share/applications/eclipse-files.desktop`,
    terminalDesktop: `${home}/.local/share/applications/eclipse-terminal.desktop`,
    launcherDir,
    links: [
      { path: `${home}/Desktop/Downloads`, target: downloads },
      { path: `${home}/Desktop/outbox`, target: `${home}/outbox` },
      { path: `${home}/Desktop/work`, target: `${home}/work` },
    ],
  };
}

